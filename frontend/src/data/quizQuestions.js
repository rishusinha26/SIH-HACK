export const calculateScores = (answers) => {
  const scores = {
    logical: 0,
    creative: 0,
    quantitative: 0,
    verbal: 0,
    social: 0
  }

  answers.forEach(answer => {
    if (answer && answer.category && answer.weight) {
      scores[answer.category] += answer.weight
    }
  })

  return scores
}

export const getRecommendedStreams = (scores) => {
  const sortedScores = Object.entries(scores)
    .sort(([,a], [,b]) => b - a)
    .slice(0, 3)

  const streamMapping = {
    logical: 'Engineering',
    creative: 'Arts',
    quantitative: 'Commerce',
    verbal: 'Arts',
    social: 'Science'
  }

  return sortedScores.map(([category]) => streamMapping[category] || category)
}

